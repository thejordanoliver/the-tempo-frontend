export function resolveSoccerTeamLeague(
  teamId: string | number | undefined,
  league: string | string[] | undefined,
): string {
  const value = (Array.isArray(league) ? league[0] : league)?.trim().toLowerCase();
  if (value && value !== "socc" && value !== "soccer") return value;
  const id = Number(teamId);
  if (MSOC_TEAM_IDS.has(id)) return "msoc";
  if (WSOC_TEAM_IDS.has(id)) return "wsoc";
  return "socc";
}
