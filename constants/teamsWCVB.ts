export const getWCVBTeam = (id: number | string | undefined) => {
  if (id == null) return undefined;

  return wcvbTeams.find((t) => String(t.id) === String(id));
};

export const getWCVBTeamLogo = (id?: number | string, isDark = false) => {
  if (!id) return PlaceholderLogo;

  const team = wcvbTeams.find((t) => String(t.id) === String(id));

  if (!team) return PlaceholderLogo;
  return isDark ? (team.logoLight ?? team.logo) : team.logo;
};
