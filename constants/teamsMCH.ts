export const getMCHTeam = (id: number | string | undefined) => {
  if (id == null) return undefined;

  return mchTeams.find((t) => String(t.id) === String(id));
};

export const getMCHTeamLogo = (id?: number | string, isDark = false) => {
  if (!id) return PlaceholderLogo;

  const team = mchTeams.find((t) => String(t.id) === String(id));

  if (!team) return PlaceholderLogo;
  return isDark ? (team.logoLight ?? team.logo) : team.logo;
};
