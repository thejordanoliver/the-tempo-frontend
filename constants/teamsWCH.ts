export const getWCHTeam = (id: number | string | undefined) => {
  if (id == null) return undefined;

  return wchTeams.find((t) => String(t.id) === String(id));
};

export const getWCHTeamLogo = (id?: number | string, isDark = false) => {
  if (!id) return PlaceholderLogo;

  const team = wchTeams.find((t) => String(t.id) === String(id));

  if (!team) return PlaceholderLogo;
  return isDark ? (team.logoLight ?? team.logo) : team.logo;
};
