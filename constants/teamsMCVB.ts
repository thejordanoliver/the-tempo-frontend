export const getMCVBTeam = (id: number | string | undefined) => {
  if (id == null) return undefined;

  return mcvbTeams.find((t) => String(t.id) === String(id));
};

export const getMCVBTeamLogo = (id?: number | string, isDark = false) => {
  if (!id) return PlaceholderLogo;

  const team = mcvbTeams.find((t) => String(t.id) === String(id));

  if (!team) return PlaceholderLogo;
  return isDark ? (team.logoLight ?? team.logo) : team.logo;
};
